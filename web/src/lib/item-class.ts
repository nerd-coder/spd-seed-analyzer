export type ItemClass = (typeof ItemClass)[keyof typeof ItemClass]

const ITEM_CLASS_VALUES = new Set<string>(Object.values(ItemClass))

/** Report class name to `ItemClass`, or `undefined` when the name is unknown. */
export function parseItemClass(
  value: string | null | undefined
): ItemClass | undefined {
  if (value != null && ITEM_CLASS_VALUES.has(value)) return value as ItemClass
  return undefined
}
